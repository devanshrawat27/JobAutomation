import { prisma } from "@/lib/db";
import { renderCoverLetterPdf, renderResumePdf, type ResumePdfData } from "@/lib/documents/pdf";
import { getCurrentSession } from "@/lib/session";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

function slug(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 40) || "document";
}

export async function GET(_request: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;

  const session = await getCurrentSession();
  if (!session?.user) return new Response("Sign in to download this document.", { status: 401 });

  const document = await prisma.document.findFirst({
    where: { id, userId: session.user.id },
  });
  if (!document) return new Response("Not found.", { status: 404 });

  const footer = `${document.company} · ${document.postingTitle} · ${document.factKeys.length} confirmed facts cited · generated by jobautomation`;

  const buffer =
    document.kind === "RESUME"
      ? await renderResumePdf((document.data as ResumePdfData | null) ?? {}, footer)
      : await renderCoverLetterPdf(`Cover letter — ${document.postingTitle}`, document.content, footer);

  const filename = `${slug(document.company)}-${slug(document.postingTitle)}-${document.kind === "RESUME" ? "resume" : "cover-letter"}.pdf`;

  return new Response(new Uint8Array(buffer), {
    headers: {
      "content-type": "application/pdf",
      "content-disposition": `attachment; filename="${filename}"`,
      "cache-control": "private, no-store",
    },
  });
}
